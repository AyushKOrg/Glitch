const { requireUser, consumeGuestMessage } = require('./_lib');
const pptxgen = require('pptxgenjs');

const MODEL = process.env.GEMINI_MODEL || 'gemini-3.5-flash-lite';
const MIME = 'application/vnd.openxmlformats-officedocument.presentationml.presentation';

function cleanText(value, max = 220) {
  return String(value || '').replace(/[\u0000-\u001f]/g, ' ').replace(/\s+/g, ' ').trim().slice(0, max);
}
function parseDeck(text) {
  const raw = String(text || '').trim();
  const start = raw.indexOf('{'), end = raw.lastIndexOf('}');
  if (start < 0 || end <= start) throw new Error('The slide planner returned invalid JSON. Please try again.');
  let data;
  try { data = JSON.parse(raw.slice(start, end + 1)); }
  catch { throw new Error('The slide planner returned malformed slide data. Please try again.'); }
  if (!Array.isArray(data.slides) || !data.slides.length) throw new Error('The slide planner returned no slides. Please try again.');
  data.title = cleanText(data.title, 100) || 'Presentation';
  data.subtitle = cleanText(data.subtitle, 180);
  data.slides = data.slides.slice(0, 12).map((slide, i) => ({
    title: cleanText(slide && slide.title, 90) || (i === 0 ? data.title : 'Key idea'),
    bullets: (Array.isArray(slide && slide.bullets) ? slide.bullets : []).map(x => cleanText(x, 240)).filter(Boolean).slice(0, 5),
    takeaway: cleanText(slide && slide.takeaway, 220),
    layout: slide && slide.layout === 'closing' ? 'closing' : 'content',
  }));
  return data;
}
function addText(slide, text, opts) {
  slide.addText(String(text || ''), { margin: 0, breakLine: false, ...opts });
}
function buildPresentation(deck) {
  const pptx = new pptxgen();
  pptx.layout = 'LAYOUT_WIDE';
  pptx.author = 'Glitch';
  pptx.subject = 'Presentation generated by Glitch';
  pptx.title = deck.title;
  pptx.company = 'Glitch';
  pptx.lang = 'en-US';
  pptx.theme = {
    headFontFace: 'Aptos Display',
    bodyFontFace: 'Aptos',
    lang: 'en-US',
  };
  pptx.defineSlideMaster({
    title: 'GLITCH_MASTER',
    background: { color: '0B1020' },
    objects: [
      { rect: { x: 0, y: 0, w: 0.12, h: 7.5, line: { color: '7C3AED', transparency: 100 }, fill: { color: '7C3AED' } } },
      { text: { text: 'GLITCH  /  IDEAS INTO ACTION', options: { x: 0.55, y: 7.08, w: 5.8, h: 0.18, fontFace: 'Aptos', fontSize: 8, color: '94A3B8', charSpacing: 1.2, margin: 0 } } },
      { text: { text: 'GENERATED WITH GLITCH', options: { x: 8.0, y: 7.08, w: 4.7, h: 0.18, fontFace: 'Aptos', fontSize: 8, color: '64748B', align: 'right', margin: 0 } } },
    ],
    slideNumber: { x: 12.25, y: 0.28, color: '94A3B8', fontFace: 'Aptos', fontSize: 9 },
  });
  const addCover = () => {
    const slide = pptx.addSlide();
    slide.background = { color: '0B1020' };
    slide.addShape(pptx.ShapeType.rect, { x: 0.78, y: 0.82, w: 1.15, h: 0.08, line: { color: 'A78BFA', transparency: 100 }, fill: { color: 'A78BFA' } });
    addText(slide, 'GLITCH', { x: 0.82, y: 1.18, w: 3, h: 0.35, fontFace: 'Aptos', fontSize: 16, bold: true, charSpacing: 4, color: 'C4B5FD' });
    addText(slide, deck.title, { x: 0.82, y: 2.0, w: 10.9, h: 1.65, fontFace: 'Aptos Display', fontSize: 34, bold: true, color: 'F8FAFC', breakLine: false, valign: 'mid', fit: 'shrink' });
    if (deck.subtitle) addText(slide, deck.subtitle, { x: 0.86, y: 4.05, w: 9.8, h: 0.72, fontSize: 18, color: 'A5B4FC', breakLine: false, valign: 'top', fit: 'shrink' });
    slide.addShape(pptx.ShapeType.roundRect, { x: 0.85, y: 5.55, w: 2.45, h: 0.5, rectRadius: 0.12, line: { color: '7C3AED', transparency: 100 }, fill: { color: '7C3AED' } });
    addText(slide, 'A GLITCH PERSPECTIVE', { x: 1.02, y: 5.71, w: 2.1, h: 0.14, fontSize: 9, bold: true, charSpacing: 1, color: 'FFFFFF', align: 'center' });
  };
  addCover();
  for (const item of deck.slides) {
    const slide = pptx.addSlide('GLITCH_MASTER');
    addText(slide, item.title, { x: 0.72, y: 0.62, w: 11.75, h: 0.78, fontFace: 'Aptos Display', fontSize: 27, bold: true, color: 'F8FAFC', fit: 'shrink', valign: 'mid' });
    slide.addShape(pptx.ShapeType.line, { x: 0.74, y: 1.52, w: 1.05, h: 0, line: { color: 'A78BFA', width: 3 } });
    if (item.layout === 'closing') {
      addText(slide, item.takeaway || 'Make the next move count.', { x: 1.0, y: 2.45, w: 10.8, h: 1.5, fontFace: 'Aptos Display', fontSize: 30, bold: true, color: 'DDD6FE', align: 'center', valign: 'mid', fit: 'shrink' });
      if (item.bullets.length) addText(slide, item.bullets.join('   •   '), { x: 1.0, y: 4.55, w: 10.8, h: 0.8, fontSize: 15, color: 'CBD5E1', align: 'center', valign: 'mid', fit: 'shrink' });
      continue;
    }
    const bullets = item.bullets.length ? item.bullets : ['A clear idea becomes useful when it leads to a concrete next step.'];
    const top = 1.95, gap = Math.min(0.88, 4.2 / bullets.length);
    bullets.forEach((bullet, i) => {
      const y = top + i * gap;
      slide.addShape(pptx.ShapeType.ellipse, { x: 0.86, y: y + 0.11, w: 0.15, h: 0.15, line: { color: 'A78BFA', transparency: 100 }, fill: { color: 'A78BFA' } });
      addText(slide, bullet, { x: 1.22, y, w: 10.8, h: gap - 0.08, fontSize: 17, color: 'E2E8F0', valign: 'mid', breakLine: false, fit: 'shrink' });
    });
    if (item.takeaway) {
      slide.addShape(pptx.ShapeType.roundRect, { x: 0.82, y: 6.12, w: 11.55, h: 0.58, rectRadius: 0.08, line: { color: '312E81', transparency: 100 }, fill: { color: '17152F' } });
      addText(slide, item.takeaway, { x: 1.08, y: 6.29, w: 11.0, h: 0.18, fontSize: 11, bold: true, color: 'C4B5FD', fit: 'shrink' });
    }
  }
  return pptx.write({ outputType: 'nodebuffer' });
}

module.exports = async (req, res) => {
  res.setHeader('Cache-Control', 'no-store');
  if (req.method !== 'POST') return res.status(405).json({ error: 'POST only.' });
  const user = await requireUser(req, res);
  if (!user) return;
  if (!process.env.GOOGLE_API_KEY) return res.status(503).json({ error: 'PowerPoint generation needs GOOGLE_API_KEY in the Glitch Vercel environment.' });
  const prompt = cleanText(req.body && req.body.prompt, 4000);
  if (!prompt) return res.status(400).json({ error: 'Add a topic or prompt for the presentation.' });
  if (user.isAnonymous) {
    let usage;
    try { usage = await consumeGuestMessage(user); }
    catch (e) { return res.status(503).json({ error: e.message || 'Guest quota could not be checked.' }); }
    if (!usage || usage.allowed !== true) return res.status(429).json({ error: 'You have used all 30 free guest messages. Sign in to continue.' });
  }
  try {
    const instruction = [
      'Create a polished, presentation-ready PowerPoint slide deck.',
      'Return ONLY valid JSON with this exact shape: {"title":"...","subtitle":"...","slides":[{"title":"...","bullets":["..."],"takeaway":"...","layout":"content"}]}.',
      'Create 6 to 9 concise slides, not counting the cover slide that the app adds.',
      'Each slide must have 2 to 5 specific, useful bullets. Keep each bullet under 25 words.',
      'Use a logical narrative: context, key arguments, concrete examples, balanced caveats, practical conclusion.',
      'Do not invent statistics, customer counts, testimonials, benchmarks, or product capabilities. Clearly frame opinions as opinions.',
      'The final slide should use layout "closing" and contain a strong, memorable takeaway.',
      'Avoid markdown fences and all text outside the JSON object.',
      'User request: ' + prompt,
    ].join('\n');
    const geminiUrl = 'https://generativelanguage.googleapis.com/v1beta/models/' + encodeURIComponent(MODEL) + ':generateContent';
    const geminiBody = {
      contents: [{ role: 'user', parts: [{ text: instruction }] }],
      generationConfig: { responseMimeType: 'application/json', maxOutputTokens: 7000, temperature: 0.55 },
    };
    let raw = '';
    let geminiFailure = null;
    // Google can return transient 503/429 overloads. Retry briefly, then use the
    // already-configured free OpenRouter model rather than returning an empty reply.
    for (let attempt = 0; attempt < 2; attempt++) {
      try {
        const response = await fetch(geminiUrl, {
          method: 'POST',
          headers: { 'Content-Type': 'application/json', 'x-goog-api-key': process.env.GOOGLE_API_KEY },
          body: JSON.stringify(geminiBody),
          signal: AbortSignal.timeout(25000),
        });
        if (!response.ok) {
          const detail = (await response.text()).slice(0, 220);
          const error = new Error('Gemini returned ' + response.status + ': ' + detail);
          error.status = response.status;
          throw error;
        }
        const payload = await response.json();
        const candidate = payload.candidates && payload.candidates[0];
        raw = candidate && candidate.content && candidate.content.parts ? candidate.content.parts.map(p => p.text || '').join('') : '';
        if (!raw.trim()) throw new Error('Gemini returned an empty slide plan.');
        break;
      } catch (error) {
        geminiFailure = error;
        const retryable = [429, 500, 502, 503, 504].includes(Number(error.status)) ||
          /timeout|temporar|overload|empty slide plan/i.test(String(error.message || ''));
        if (attempt === 0 && retryable) {
          await new Promise(resolve => setTimeout(resolve, 900));
          continue;
        }
        break;
      }
    }
    if (!raw.trim() && process.env.OPENROUTER_API_KEY) {
      const fallbackModel = process.env.OPENROUTER_MODEL || 'nvidia/nemotron-3-ultra-550b-a55b:free';
      const fallback = await fetch('https://openrouter.ai/api/v1/chat/completions', {
        method: 'POST',
        headers: { 'Content-Type': 'application/json', Authorization: 'Bearer ' + process.env.OPENROUTER_API_KEY },
        body: JSON.stringify({
          model: fallbackModel,
          messages: [
            { role: 'system', content: 'You create polished PowerPoint slide plans. Return only valid JSON with title, subtitle, and slides. Each slide has title, bullets, takeaway, and layout. Do not invent statistics or product capabilities.' },
            { role: 'user', content: instruction },
          ],
          max_tokens: 7000,
          response_format: { type: 'json_object' },
        }),
        signal: AbortSignal.timeout(35000),
      });
      if (!fallback.ok) throw new Error('Gemini was temporarily overloaded (' + (geminiFailure && geminiFailure.status || 'unavailable') + ') and the free backup model returned ' + fallback.status + '. Please retry shortly.');
      const fallbackData = await fallback.json();
      raw = String(fallbackData.choices && fallbackData.choices[0] && fallbackData.choices[0].message && fallbackData.choices[0].message.content || '').trim();
      if (!raw) throw new Error('Both Gemini and the free backup model returned an empty slide plan. Please retry.');
    }
    if (!raw.trim()) {
      const status = geminiFailure && geminiFailure.status;
      if (status === 503 || status === 429) {
        return res.status(503).json({ error: 'Gemini is temporarily overloaded, and no OpenRouter backup key is configured. Please retry in a minute.' });
      }
      throw geminiFailure || new Error('The slide planner returned an empty response. Try again with a more specific topic.');
    }
    const deck = parseDeck(raw);
    const buffer = await buildPresentation(deck);
    const filename = (deck.title.toLowerCase().replace(/[^a-z0-9]+/g, '-').replace(/^-|-$/g, '').slice(0, 60) || 'glitch-presentation') + '.pptx';
    return res.status(200).json({
      filename,
      mimeType: MIME,
      pptxBase64: buffer.toString('base64'),
      reply: 'Your PowerPoint is ready: **' + deck.title + '**. I generated the editable slide deck and started the download.',
    });
  } catch (error) {
    return res.status(502).json({ error: error.message || 'PowerPoint generation failed. Please try again.' });
  }
};
